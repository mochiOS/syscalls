#!/usr/bin/env python3
"""Generate the fixed-arclength minimum curvature-variation corner. No dependencies.

Composite Simpson integration is performed offline, never by a renderer.
Run from any directory; the generated Rust table is checked into source control.
"""
from pathlib import Path
import math
import subprocess
import argparse

C = 1.6525000895846302
N = 1024

def tangent(t):
    angle = math.pi / 2 * (3 * t * t - 2 * t * t * t)
    return math.cos(angle), math.sin(angle)

nodes = [(0.0, 0.0, 1.0, 0.0)]
x = y = 0.0
for i in range(N):
    # 16 subintervals per table interval; double precision integration.
    h = 1 / N / 16
    sx = sy = 0.0
    for j in range(17):
        a, b = tangent(i / N + j * h)
        weight = 1 if j in (0, 16) else (4 if j % 2 else 2)
        sx += weight * a
        sy += weight * b
    x += C * h / 3 * sx
    y += C * h / 3 * sy
    nodes.append((x, y, *tangent((i + 1) / N)))
nodes[-1] = (1.0, 1.0, 0.0, 1.0)
output = Path(__file__).resolve().parents[1] / 'src/continuous_corner_data.rs'
with output.open('w') as out:
    out.write('// Generated by tools/generate_continuous_corner.py; do not edit.\n')
    out.write('// [X(t), Y(t), cos(theta(t)), sin(theta(t))], t = index / 1024.\n')
    out.write('pub(super) const NODES: [[f64; 4]; 1025] = [\n')
    for row in nodes:
        out.write('    [' + ', '.join(f'{v:.17e}' for v in row) + '],\n')
    out.write('];\n')

subprocess.run(["rustfmt", "--edition", "2024", str(output)], check=True)

# Firmware keeps BootUI dependency-free. Export the identical geometry and test
# vectors instead of making a UEFI renderer depend on a desktop transport crate.
parser = argparse.ArgumentParser()
parser.add_argument('--bootui', type=Path, help='Export identical source/data into BootUI src/')
args = parser.parse_args()
if args.bootui:
    source = output.with_name('continuous_corner.rs')
    args.bootui.mkdir(parents=True, exist_ok=True)
    for file in (source, output):
        (args.bootui / file.name).write_bytes(file.read_bytes())
